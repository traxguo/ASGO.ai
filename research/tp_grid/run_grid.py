#!/usr/bin/env python3
"""
Stage 3 (PROJECT_BRIEF 7.3): run the fixed TP variant grid for one strategy on
DEVELOPMENT data only, and write a comparison table in R.

The grid comes from strategies.common.trade_management.tp_variant_grid() and is
never extended. Identical variants (e.g. pct=0 with be=2R differ only in an
unused TP1) are run once.

Usage (from repo root, after FT_LOCAL=1 FT_OFFLINE=1 env if needed):
  python research/tp_grid/run_grid.py --module donchian_breakout --base DonchianBreakout_B \
      --timerange 20200101-20250101 --out results/2026-10-08_donchian_breakout_tp_izgara
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import pandas as pd  # noqa: E402

from strategies.common.trade_management import tp_variant_grid  # noqa: E402

GEN_DIR = ROOT / "user_data" / "tp_grid_strategies"  # generated, gitignored
RES_DIR = ROOT / "user_data" / "tp_grid_results"


def unique_grid():
    seen, out = set(), []
    for m in tp_variant_grid():
        # Without a partial exit, TP1 only sets the break-even level.
        if m.tp1_close_pct == 0:
            key = (m.tp2_r, 0, m.breakeven_r)
        else:
            key = (m.tp2_r, m.tp1_close_pct, m.tp1_r, m.breakeven_trigger)
        if key not in seen:
            seen.add(key)
            out.append(m)
    return out


def class_name(i: int) -> str:
    return f"Grid{i:02d}"


def write_module(module: str, base: str, src_dir: str, models) -> None:
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / src_dir / f"{module}.py", GEN_DIR / f"{module}.py")
    lines = [
        '"""Generated by research/tp_grid/run_grid.py. Do not edit."""',
        "import sys",
        f"sys.path.insert(0, {str(ROOT)!r})",
        f"sys.path.insert(0, {str(GEN_DIR)!r})",
        "from strategies.common.trade_management import TPModel",
        f"from {module} import {base}",
        "",
    ]
    for i, m in enumerate(models):
        lines += [
            f"class {class_name(i)}({base}):",
            f"    tp_model_name = {m.name!r}",
            f"    tp_model = TPModel({m.name!r}, {m.tp1_r}, {m.tp2_r}, {m.tp1_close_pct}, {m.breakeven_trigger!r})",
            "",
        ]
    (GEN_DIR / "tp_grid_generated.py").write_text("\n".join(lines))


def summarize(result_file: Path, models, base_tf: str) -> pd.DataFrame:
    import make_report as mr
    from freqtrade.data.btanalysis import load_backtest_stats

    stats = load_backtest_stats(result_file)
    rows = []
    for i, m in enumerate(models):
        s = stats["strategy"][class_name(i)]
        rt = pd.DataFrame([mr.trade_r(t) for t in s["trades"]])
        long_r = rt.loc[rt.side == "long", "r"].sum()
        short_r = rt.loc[rt.side == "short", "r"].sum()
        rows.append({
            "Varyant": m.name, "TP1 (R)": m.tp1_r, "TP2 (R)": m.tp2_r, "TP1'de kapat %": m.tp1_close_pct,
            "BE tetiği": m.breakeven_trigger, "İşlem": len(rt), "Ortalama R": rt.r.mean(),
            "Long R": long_r, "Short R": short_r, "Profit factor": s["profit_factor"],
            "Net getiri %": s["profit_total"] * 100, "Max DD %": s["max_drawdown_account"] * 100,
        })
    return pd.DataFrame(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--module", required=True)
    ap.add_argument("--base", required=True, help="strategy class to subclass")
    ap.add_argument("--src-dir", default="strategies/candidates")
    ap.add_argument("--timeframe", default="4h")
    ap.add_argument("--timerange", default="20200101-20250101")
    ap.add_argument("--fee", type=float)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    if a.timerange.split("-")[1] > "20250101":
        sys.exit("TP grid runs on development data only (ends 20250101).")

    models = unique_grid()
    write_module(a.module, a.base, a.src_dir, models)
    shutil.rmtree(RES_DIR, ignore_errors=True)
    RES_DIR.mkdir(parents=True)
    cmd = ["./scripts/ft.sh", "backtesting", "--strategy-list", *[class_name(i) for i in range(len(models))],
           "--timeframe", a.timeframe, "--timerange", a.timerange, "--export", "trades",
           "--backtest-directory", str(RES_DIR), "--cache", "none"]
    if a.fee is not None:
        cmd += ["--fee", str(a.fee)]
    env = dict(os.environ, FT_STRATEGY_DIR=str(GEN_DIR.relative_to(ROOT)))
    log = RES_DIR / "backtest.log"
    with log.open("w") as fh:
        subprocess.run(cmd, cwd=ROOT, env=env, stdout=fh, stderr=subprocess.STDOUT, check=True)
    if "ERROR" in log.read_text():
        sys.exit(f"errors in backtest log: {log}")
    result = next(RES_DIR.glob("*.zip"))
    df = summarize(result, models, a.timeframe).sort_values("Ortalama R", ascending=False)

    out = ROOT / a.out
    out.mkdir(parents=True, exist_ok=True)
    fmt = {"Ortalama R": "{:+.3f}", "Long R": "{:+.1f}", "Short R": "{:+.1f}", "Profit factor": "{:.2f}",
           "Net getiri %": "{:+.1f}", "Max DD %": "{:.1f}"}
    table = df.copy()
    for c, f in fmt.items():
        table[c] = table[c].map(f.format)
    header = "| " + " | ".join(table.columns) + " |\n|" + "---|" * len(table.columns) + "\n"
    body = "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in table.itertuples(index=False))
    (out / "izgara.md").write_text(
        f"# TP model ızgarası — {a.base} — {a.timerange}" + (f" — fee {a.fee}" if a.fee else "") + "\n\n"
        "Sadece geliştirme verisi. Maliyet + funding dahil. Ortalama R'ye göre sıralı.\n\n" + header + body)
    df.to_csv(out / ("izgara" + ("_fee2x" if a.fee else "") + ".csv"), index=False)
    print(out / "izgara.md")
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
