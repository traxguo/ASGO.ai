#!/usr/bin/env python3
"""
Stage 5 parameter stability (PROJECT_BRIEF 8): each parameter moved -20% and +20%
one at a time, everything else fixed. Development data only unless --timerange says otherwise.

  python research/robustness/param_neighbors.py --module atr_filtered --base DonchianATR_B \
      --param channel=int:20 --param vol_window=attr:200 --out results/<folder>
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import pandas as pd  # noqa: E402

GEN_DIR = ROOT / "user_data" / "neighbor_strategies"
RES_DIR = ROOT / "user_data" / "neighbor_results"


def variants(params: list[str]):
    out = [("base", None, None, None)]
    for p in params:
        name, spec = p.split("=")
        kind, value = spec.split(":")
        v = float(value)
        for mult in (0.8, 1.2):
            nv = round(v * mult) if v.is_integer() else round(v * mult, 6)
            out.append((f"{name}={nv}", name, kind, nv))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--module", required=True)
    ap.add_argument("--base", required=True)
    ap.add_argument("--src-dir", default="strategies/candidates")
    ap.add_argument("--param", action="append", required=True,
                    help="name=int:<default> (IntParameter) or name=attr:<default> (class attribute)")
    ap.add_argument("--timeframe", default="4h")
    ap.add_argument("--timerange", default="20200101-20250101")
    ap.add_argument("--out", required=True)
    ap.add_argument("--ft-arg", action="append", default=[],
                    help="extra backtesting argument, repeatable, e.g. --ft-arg=--max-open-trades --ft-arg=3")
    a = ap.parse_args()

    vs = variants(a.param)
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / a.src_dir / f"{a.module}.py", GEN_DIR / f"{a.module}.py")
    lines = ['"""Generated by research/robustness/param_neighbors.py. Do not edit."""', "import sys",
             f"sys.path.insert(0, {str(ROOT)!r})", f"sys.path.insert(0, {str(GEN_DIR)!r})",
             "from freqtrade.strategy import IntParameter", f"from {a.module} import {a.base}", ""]
    for i, (_, name, kind, nv) in enumerate(vs):
        lines.append(f"class Nb{i:02d}({a.base}):")
        if name is None:
            lines.append("    pass")
        elif kind == "int":
            lines.append(f"    {name} = IntParameter(1, 1000, default={nv}, space='buy', optimize=False)")
        else:
            lines.append(f"    {name} = {nv}")
        lines.append("")
    (GEN_DIR / "neighbors_generated.py").write_text("\n".join(lines))

    shutil.rmtree(RES_DIR, ignore_errors=True)
    RES_DIR.mkdir(parents=True)
    cmd = ["./scripts/ft.sh", "backtesting", "--strategy-list", *[f"Nb{i:02d}" for i in range(len(vs))],
           "--timeframe", a.timeframe, "--timerange", a.timerange, "--export", "trades",
           "--backtest-directory", str(RES_DIR), "--cache", "none", *a.ft_arg]
    env = dict(os.environ, FT_STRATEGY_DIR=str(GEN_DIR.relative_to(ROOT)))
    log = RES_DIR / "backtest.log"
    with log.open("w") as fh:
        subprocess.run(cmd, cwd=ROOT, env=env, stdout=fh, stderr=subprocess.STDOUT, check=True)
    if "ERROR" in log.read_text():
        sys.exit(f"errors in backtest log: {log}")

    import make_report as mr
    from freqtrade.data.btanalysis import load_backtest_stats
    stats = load_backtest_stats(next(RES_DIR.glob("*.zip")))
    rows = []
    for i, (label, *_ ) in enumerate(vs):
        s = stats["strategy"][f"Nb{i:02d}"]
        rt = pd.DataFrame([mr.trade_r(t) for t in s["trades"]])
        rows.append({"Varyant": label, "İşlem": len(rt), "Ortalama R": f"{rt.r.mean():+.3f}",
                     "Profit factor": f"{s['profit_factor']:.2f}", "Net getiri %": f"{s['profit_total']*100:+.1f}",
                     "Max DD %": f"{s['max_drawdown_account']*100:.1f}"})
    df = pd.DataFrame(rows)
    out = ROOT / a.out
    out.mkdir(parents=True, exist_ok=True)
    header = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    body = "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in df.itertuples(index=False))
    (out / "parametre_komsulari.md").write_text(
        f"# Parametre kararlılığı (±%20) — {a.base} — {a.timerange}\n\nHer seferinde tek parametre değişti. "
        "Maliyet + funding dahil.\n\n" + header + body)
    print(df.to_string(index=False))


if __name__ == "__main__":
    main()
